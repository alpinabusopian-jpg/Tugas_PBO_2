package Prak_05;

public class soal8 {
    public static void main(String[] args) {
        int[] angka = {10, 20, 30, 40, 50};
        String[] buah = {"Apel", "Jeruk", "Mangga"};

        System.out.println("Isi array angka:");
        for (int nilai : angka) {
            System.out.println(nilai);
        }

        System.out.println("Isi array buah:");
        for (String b : buah) {
            System.out.println(b);
        }
    }
}
